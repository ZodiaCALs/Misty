def G(x):
    """A CSS number without trailing zeros."""
    s = f"{float(x):.6f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def F(x):
    return repr(float(x))


def I(x):
    return str(int(x)) if float(x).is_integer() else repr(float(x))


def camel(short):
    short = {"nav-h": "nav-height", "r-2xl": "r-xxl"}.get(short, short)
    parts = short.split("-")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(short):
    c = camel(short)
    return c[:1].upper() + c[1:]


def radius_key(css):
    return camel(css[len("--m-r-"):].replace("2xl", "xxl"))


def type_key(css):
    return css[len("--m-text-"):]


def layout_key(css):
    return camel(css[len("--m-"):])


def duration_key(css):
    return "duration" + css[len("--m-dur-"):]


def curve_key(css):
    return css[len("--m-ease-"):]


def follows(d):
    return d["hue"] == "relative"


def window_cases(fmt_if, fmt_else):
    out = []
    for name, limit in WINDOWS:
        out.append(fmt_if(name, limit) if limit is not None else fmt_else(name))
    return out


