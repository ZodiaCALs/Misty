def gen_swift(m):
    o = [f"// SPDX-FileCopyrightText: 2026 {OWNER}", "// SPDX-License-Identifier: Apache-2.0", "//",
         f"// Misty {VERSION} tokens for Apple platforms: iOS, iPadOS, macOS, watchOS, tvOS and",
         f"// visionOS. {GENERATED}", "", SWIFT_CORE]
    o.append("/// Every colour token, named as in CSS without the --m- prefix.")
    o.append("public enum MistyColorToken {")
    for t in m.colours():
        o.append(f"    /// `{t.css}`")
        o.append(f"    public static let {camel(t.short)} = MistyThemedColor(light: {sw_ok(t.ext['light'])}, "
                 f"dark: {sw_ok(t.ext['dark'])})")
    o.append("}\n")
    gl, gld = m.num("--m-glass-l"), m.num("--m-glass-l", True)
    gc, gcd = m.num("--m-glass-c"), m.num("--m-glass-c", True)
    o.append("/// Glass: a tint of the field at a grade's alpha, over a blur of what lies behind.")
    o.append("public enum MistyGlass {")
    o.append(f"    public static let lightness = (light: {F(gl)}, dark: {F(gld)})")
    o.append(f"    public static let chroma = (light: {F(gc)}, dark: {F(gcd)})")
    o.append(f"    /// Backdrop saturation, as a multiplier.")
    o.append(f"    public static let saturation: Double = {F(m.num('--m-glass-sat'))}")
    o.append("")
    o.append("    public static func alpha(_ grade: MistyGlassGrade, _ appearance: MistyAppearance) -> Double {")
    o.append("        let dark = appearance == .dark")
    o.append("        switch grade {")
    for name, alpha, _ in GRADES:
        o.append(f"        case .{name}: return dark ? {F(m.num(alpha, True))} : {F(m.num(alpha))}")
    o.append("        }\n    }\n")
    o.append("    /// The blur's standard deviation in points, as in CSS.")
    o.append("    public static func blur(_ grade: MistyGlassGrade) -> CGFloat {")
    o.append("        switch grade {")
    for name, _, blur in GRADES:
        o.append(f"        case .{name}: return {I(m.px(blur))}")
    o.append("        }\n    }\n}\n")
