def same(a, b):
    if isinstance(a, float) or isinstance(b, float):
        return isinstance(a, (int, float)) and isinstance(b, (int, float)) and abs(a - b) < 1e-9
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(same(a[k], b[k]) for k in a)
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(same(x, y) for x, y in zip(a, b))
    return a == b


def check(css_path):
    want = load()
    have = Model(tokens_from_css(css_path))
    problems = []
    for t in want.tokens:
        other = have.by.get(t.css)
        if other is None:
            problems.append(f"{t.css} is missing from {css_path}")
            continue
        drop = lambda raw: {k: v for k, v in raw.items() if k != "$value"} if raw["$type"] == "shadow" else raw
        if not same(drop(t.raw), drop(other.raw)):
            problems.append(f"{t.css} differs")
    problems += [f"{n} is in {css_path} but not in the token file" for n in have.by if n not in want.by]
    for p in problems:
        print("  " + p)
    print(f"{css_path}: {'matches the token file' if not problems else f'{len(problems)} difference(s)'} "
          f"({len(have.tokens)} tokens)")
    return 1 if problems else 0


