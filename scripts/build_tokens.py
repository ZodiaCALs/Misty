def css_colour(d):
    if follows(d):
        h = "var(--m-hue)" if d["h"] == 0 else f"calc(var(--m-hue) {'+' if d['h'] > 0 else '-'} {G(abs(d['h']))})"
    else:
        h = G(d["h"])
    return f"oklch({G(d['l'])} {G(d['c'])} {h})" if d["alpha"] == 1 else f"oklch({G(d['l'])} {G(d['c'])} {h} / {G(d['alpha'])})"


def css_value(t, dark=False):
    e = t.ext
    if t.type == "color":
        return css_colour(e["dark" if dark else "light"])
    if t.type == "shadow":
        return ", ".join(f"{G(l['x'])}px {G(l['y'])}px {G(l['blur'])}px {G(l['spread'])}px "
                         + (f"var({l['ref']})" if "ref" in l else css_colour(l["color"]))
                         for l in e["dark" if dark else "light"])
    if t.type == "fontFamily":
        return ", ".join(f'"{f}"' if " " in f else f for f in t.value)
    if t.type == "dimension":
        if "fluid" in e:
            f = e["fluid"]
            return f"clamp({G(f['min'])}rem, {G(f['vw'])}vw, {G(f['max'])}rem)"
        return f"{G(t.value['value'])}{t.value['unit']}"
    if t.type == "duration":
        return f"{G(t.value['value'])}ms"
    if t.type == "cubicBezier":
        return "cubic-bezier(" + ", ".join(G(x) for x in t.value) + ")"
    v = e.get("dark", t.value) if dark else t.value
    if e.get("unit") == "%":
        return f"{G(v * 100)}%"
    if e.get("unit") == "ch":
        return f"{G(v)}ch"
    return G(v)


def gen_css(m):
    themed = [t for t in m.tokens if t.ext.get("themed")]
    out = [f"/* SPDX-FileCopyrightText: 2026 {OWNER}", "   SPDX-License-Identifier: Apache-2.0", "",
           f"   Misty {VERSION} tokens only, for products that bring their own components.",
           f"   {GENERATED} */", "", ":root {"]
    out += [f"  {t.css}: {css_value(t)};" for t in m.tokens] + ["  color-scheme: light;", "}", "",
                                                              '[data-theme="dark"] {']
    out += [f"  {t.css}: {css_value(t, True)};" for t in themed] + ["  color-scheme: dark;", "}", "",
                                                                  "@media (prefers-color-scheme: dark) {",
                                                                  '  :root:not([data-theme="light"]) {']
    out += [f"    {t.css}: {css_value(t, True)};" for t in themed] + ["    color-scheme: dark;", "  }", "}", "",
                                                                    '[data-theme="light"] {']
    out += [f"  {t.css}: {css_value(t)};" for t in themed] + ["  color-scheme: light;", "}", ""]
    return "\n".join(out)


def gen_dtcg(m, dark):
    doc = copy.deepcopy(m.doc)
    paths = {t.css: f"{t.group}.{t.key}" for t in m.tokens}
    doc["$description"] = (f"Misty {VERSION} tokens, {'dark' if dark else 'light'} appearance, resolved at hue "
                           f"{int(HUE)}. {GENERATED}")
    doc["$extensions"] = {EXT: {"version": VERSION, "appearance": "dark" if dark else "light", "hue": HUE}}
    for t in m.tokens:
        raw = doc[t.group][t.key]
        e = t.ext
        keep = {"css": t.css}
        if t.type == "color":
            raw["$value"] = dtcg_color(e["dark" if dark else "light"])
        elif t.type == "shadow":
            raw["$value"] = dtcg_shadow(e["dark" if dark else "light"], paths)
        elif t.type == "number":
            raw["$value"] = e.get("dark", t.value) if dark else t.value
            if "unit" in e:
                keep["unit"] = e["unit"]
        elif "fluid" in e:
            keep["fluid"] = e["fluid"]
        raw["$extensions"] = {EXT: keep}
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


