JS_CORE = r'''/** sRGB channels from 0 to 255 for an OKLCH colour, clipped per channel as browsers do. */
export function oklchToRgb(l, c, h) {
  const angle = (h * Math.PI) / 180;
  const a = c * Math.cos(angle);
  const b = c * Math.sin(angle);
  const l3 = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m3 = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s3 = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const encode = (v) => {
    const g = v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
    return Math.floor(Math.min(1, Math.max(0, g)) * 255 + 0.5);
  };
  return [
    encode(4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3),
    encode(-1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3),
    encode(-0.0041960863 * l3 - 0.7034186147 * m3 + 1.707614701 * s3),
  ];
}

function toColor([r, g, b], alpha) {
  const hex = `#${[r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("")}`;
  return { r, g, b, alpha, hex, css: alpha === 1 ? hex : `rgba(${r}, ${g}, ${b}, ${alpha})` };
}

/** Resolve one colour token. Returns { r, g, b, alpha, hex, css }. */
export function resolveColor(name, { hue = defaultHue, appearance = "light" } = {}) {
  const token = colorTokens[name];
  if (!token) throw new Error(`Unknown Misty colour token: ${name}`);
  const [l, c, h, alpha, followsHue] = token[appearance === "dark" ? "dark" : "light"];
  return toColor(oklchToRgb(l, c, followsHue ? hue + h : h), alpha);
}

/** Every colour token resolved for one hue and appearance, as CSS colour strings. */
export function theme({ hue = defaultHue, appearance = "light" } = {}) {
  return Object.fromEntries(Object.keys(colorTokens).map((name) => [name, resolveColor(name, { hue, appearance }).css]));
}

/** The fill of a glass grade, before blur: "clear", "mist" or "veil". */
export function glassFill(grade, { hue = defaultHue, appearance = "light" } = {}) {
  const dark = appearance === "dark";
  const alpha = glass.alpha[grade][dark ? "dark" : "light"];
  return toColor(oklchToRgb(glass.lightness[dark ? "dark" : "light"], glass.chroma[dark ? "dark" : "light"], hue), alpha);
}

const clamp = (low, value, high) => Math.min(Math.max(low, value), high);
'''


