def group_of(short):
    for group, pattern, _ in GROUPS:
        if re.fullmatch(pattern, short):
            return group
    raise SystemExit(f"Unknown token --m-{short}. Add it to GROUPS in scripts/build_tokens.py.")


def split_top(text):
    """Split on commas that are not inside parentheses."""
    parts, depth, current = [], 0, ""
    for ch in text:
        depth += (ch == "(") - (ch == ")")
        if ch == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        parts.append(current.strip())
    return parts


def parse_oklch(text):
    m = OKLCH.fullmatch(text.strip())
    if not m:
        return None
    if m.group(3).startswith("var"):
        h, mode = 0.0, "relative"
    elif m.group(3).startswith("calc"):
        h, mode = float(m.group(5)) * (1 if m.group(4) == "+" else -1), "relative"
    else:
        h, mode = float(m.group(3)), "fixed"
    return {"l": float(m.group(1)), "c": float(m.group(2)), "h": h,
            "alpha": float(m.group(6)) if m.group(6) else 1.0, "hue": mode}


def parse_shadow(text):
    layers = []
    for part in split_top(text):
        m = re.match(r"((?:-?[\d.]+(?:px)?\s+){2,4})(.+)$", part)
        if not m:
            raise SystemExit(f"Can't read shadow layer: {part}")
        nums = [float(x.replace("px", "")) for x in m.group(1).split()] + [0.0, 0.0]
        layer = {"x": nums[0], "y": nums[1], "blur": nums[2] if len(m.group(1).split()) > 2 else 0.0,
                 "spread": nums[3] if len(m.group(1).split()) > 3 else 0.0}
        colour = m.group(2).strip()
        ref = re.fullmatch(r"var\((--m-[a-z0-9-]+)\)", colour)
        if ref:
            layer["ref"] = ref.group(1)
        else:
            layer["color"] = parse_oklch(colour)
            if layer["color"] is None:
                raise SystemExit(f"Can't read shadow colour: {colour}")
        layers.append(layer)
    return layers


def css_block(css, selector):
    start = css.index(selector + " {")
    end = css.index("}", start)
    return {name: " ".join(value.split())
            for name, value in re.findall(r"(--m-[a-z0-9-]+)\s*:\s*([^;]+);", css[start:end])}


def dtcg_color(defn, hue=HUE):
    h = (hue + defn["h"]) % 360 if defn["hue"] == "relative" else defn["h"]
    return {"colorSpace": "oklch", "components": [defn["l"], defn["c"], round(h, 4)],
            "alpha": defn["alpha"], "hex": to_hex(oklch_to_srgb(defn["l"], defn["c"], h))}


def px(value):
    return {"value": value, "unit": "px"}


def dtcg_shadow(layers, paths, hue=HUE):
    out = []
    for layer in layers:
        colour = "{" + paths[layer["ref"]] + "}" if "ref" in layer else dtcg_color(layer["color"], hue)
        out.append({"color": colour, "offsetX": px(layer["x"]), "offsetY": px(layer["y"]),
                    "blur": px(layer["blur"]), "spread": px(layer["spread"])})
    return out


def make_token(name, light, dark):
    """Turn one CSS custom property into (group, key, DTCG token)."""
    short = name[len("--m-"):]
    group = group_of(short)
    ext = {"css": name}
    if dark is not None:
        ext["themed"] = True

    def token(kind, value):
        return group, short, {"$type": kind, "$value": value, "$extensions": {EXT: ext}}

    colour = parse_oklch(light)
    if colour:
        ext["light"], ext["dark"] = colour, (parse_oklch(dark) if dark else colour)
        return token("color", dtcg_color(colour))
    if short.startswith("font-"):
        return token("fontFamily", [f.strip().strip('"') for f in split_top(light)])
    if light.startswith("clamp("):
        lo, vw, hi = re.fullmatch(r"clamp\(\s*([\d.]+)rem\s*,\s*([\d.]+)vw\s*,\s*([\d.]+)rem\s*\)", light).groups()
        ext["fluid"] = {"min": float(lo), "vw": float(vw), "max": float(hi)}
        return token("dimension", {"value": float(lo), "unit": "rem"})
    if light.startswith("cubic-bezier("):
        return token("cubicBezier", [float(x) for x in re.findall(r"-?[\d.]+", light)])
    if re.fullmatch(r"[\d.]+ms", light):
        return token("duration", {"value": float(light[:-2]), "unit": "ms"})
    if re.fullmatch(r"[\d.]+(?:rem|px)", light):
        unit = "rem" if light.endswith("rem") else "px"
        return token("dimension", {"value": float(light[: -len(unit)]), "unit": unit})
    if re.fullmatch(r"[\d.]+ch", light):
        ext["unit"] = "ch"
        return token("number", float(light[:-2]))
    if re.fullmatch(r"[\d.]+%", light):
        ext["unit"] = "%"
        return token("number", float(light[:-1]) / 100)
    if re.fullmatch(r"-?[\d.]+", light):
        if dark is not None:
            ext["dark"] = float(dark)
        return token("number", float(light))
    if "oklch(" in light or "var(" in light:
        ext["light"] = parse_shadow(light)
        ext["dark"] = parse_shadow(dark) if dark else ext["light"]
        return token("shadow", None)
    raise SystemExit(f"Can't read {name}: {light}")


def tokens_from_css(path):
    css = Path(path).read_text(encoding="utf-8")
    light, dark = css_block(css, ":root"), css_block(css, '[data-theme="dark"]')
    if set(dark) - set(light):
        raise SystemExit(f"Tokens declared only for dark: {sorted(set(dark) - set(light))}")
    doc = {
        "$description": "Misty design tokens. The source of truth for every platform package. Colours are given "
                        "at the default hue, 250, in the light appearance; $extensions.org.misty records how each "
                        "colour follows the hue and its value in the dark appearance.",
        "$extensions": {EXT: {"version": VERSION, "hue": {"default": HUE, "min": 0, "max": 360},
                              "conversion": "OKLCH to sRGB with the OKLab matrices of CSS Color Module Level 4, "
                                            "each channel clipped to 0..1, as browsers do on sRGB displays."}},
    }
    for group, _, description in GROUPS:
        doc[group] = {"$description": description}
    paths = {}
    for name, value in light.items():
        group, key, tok = make_token(name, value, dark.get(name))
        doc[group][key] = tok
        paths[name] = f"{group}.{key}"
    for group, _, _ in GROUPS:
        for key, tok in doc[group].items():
            if not key.startswith("$") and tok["$type"] == "shadow":
                tok["$value"] = dtcg_shadow(tok["$extensions"][EXT]["light"], paths)
    for group in [g for g, _, _ in GROUPS if len(doc[g]) == 1]:
        del doc[group]
    return doc


# ---------------------------------------------------------------------------
# The model the generators read
# ---------------------------------------------------------------------------

class Token:
    def __init__(self, group, key, raw):
        self.group, self.key, self.raw = group, key, raw
        self.type = raw["$type"]
        self.value = raw["$value"]
        self.ext = raw.get("$extensions", {}).get(EXT, {})
        self.css = self.ext["css"]
        self.short = self.css[len("--m-"):]


class Model:
    def __init__(self, doc):
        self.doc = doc
        self.tokens = [Token(g, k, t) for g, grp in doc.items() if not g.startswith("$")
                       for k, t in grp.items() if not k.startswith("$")]
        self.by = {t.css: t for t in self.tokens}
        needed = SPACE + RADII + DURATIONS + CURVES + TYPE + FLUID_LAYOUT + FIXED_LAYOUT + SHADOWS + [
            g[1] for g in GRADES] + [g[2] for g in GRADES] + ["--m-glass-l", "--m-glass-c", "--m-glass-sat", "--m-hue"]
        missing = [n for n in needed if n not in self.by]
        if missing:
            raise SystemExit(f"The token file is missing {missing}")

    def colours(self):
        return [t for t in self.tokens if t.type == "color"]

    def num(self, css, dark=False):
        t = self.by[css]
        return t.ext.get("dark", t.value) if dark else t.value

    def px(self, css):
        v = self.by[css].value
        return v["value"] * (16 if v["unit"] == "rem" else 1)

    def fluid(self, css):
        f = self.by[css].ext["fluid"]
        return f["min"] * 16, f["vw"] / 100, f["max"] * 16

    def ms(self, css):
        return self.by[css].value["value"]

    def curve(self, css):
        return self.by[css].value

    def layers(self, css, dark=False):
        return self.by[css].ext["dark" if dark else "light"]


def load(path=TOKEN_FILE):
    return Model(json.loads(Path(path).read_text(encoding="utf-8")))


